# --------------------------------------------------------------------------- #
# 字段渲染：把 prompt 里的 {字段id} 填成具体值
# --------------------------------------------------------------------------- #
def render_fields(
    prompt: str,
    fields: List[Dict[str, Any]],
    values: Dict[str, str] | None = None,
) -> str:
    """把 `{subject}` / `{actions}` 这类占位符填成字段值（缺省用 default）。

    只做字面替换：模板里的中文正文可能含别的花括号，用 format 会炸。
    """
    if not prompt:
        return prompt
    vals = values or {}
    out = prompt
    for f in fields or []:
        key = f.get("id")
        if not key:
            continue
        val = vals.get(key) or f.get("default") or ""
        out = out.replace("{" + key + "}", str(val))
    return out


def api_items() -> List[Dict[str, Any]]:
    """给前端的模板副本：prompt 里的占位符填成默认值，用户点了就能直接出图。"""
    out: List[Dict[str, Any]] = []
    for t in TEMPLATES:
        item = dict(t)
        fields = t.get("fields") or []
        item["prompt"] = render_fields(t.get("prompt", ""), fields)
        if t.get("textMode"):
            tm = dict(t["textMode"])
            tm["prompt"] = render_fields(tm.get("prompt", ""), fields)
            item["textMode"] = tm
        out.append(item)
    return out
